//! Embedded web assets for the GUI shell: HTML, stylesheets, and fonts.
//!
//! The asset table is pure string handling with no platform dependency, so it
//! lives at the crate root and is compiled on every platform, including those
//! with no webview — that is what lets `dev-web` serve exactly what the webview
//! serves. `render_index_from` takes caller-supplied shell HTML so the preview
//! server can read `web/index.html` off disk, and an edit to the shell shows up
//! on refresh like every other asset, while still going through the one
//! substitution implementation rather than growing a second copy.
//!
//! Assets are embedded from `$OUT_DIR/web`, where `build.rs` stages core's
//! `web/` tree and applies an optional brand overlay
//! (`SYSTEMPROMPT_BRIDGE_WEB_OVERLAY`) on top — a white-label repo overrides
//! any file by shipping its own copy in that overlay dir. The routing table
//! (`WEB_TEXT_ASSETS`) is generated by the same build script from the staged
//! tree, so there is no hand-maintained list to keep in sync.
//!
//! Copyright (c) systemprompt.io — Business Source License 1.1.
//! See <https://systemprompt.io> for licensing details.

use std::borrow::Cow;
use std::path::Path;

const HTML: &str = include_str!(concat!(env!("OUT_DIR"), "/web/index.html"));

include!(concat!(env!("OUT_DIR"), "/web_manifest.rs"));

const FONT_INTER_REGULAR: &[u8] = include_bytes!("../assets/fonts/Inter-Regular.woff2");
const FONT_INTER_BOLD: &[u8] = include_bytes!("../assets/fonts/Inter-Bold.woff2");
const FONT_OPENSANS_REGULAR: &[u8] = include_bytes!("../assets/fonts/OpenSans-Regular.woff2");
const FONT_OPENSANS_BOLD: &[u8] = include_bytes!("../assets/fonts/OpenSans-Bold.woff2");

const GIT_SHA_FULL: &str = env!("VERGEN_GIT_SHA");
const BUILD_DATE: &str = env!("VERGEN_GIT_COMMIT_DATE");

fn git_sha_short() -> &'static str {
    let len = GIT_SHA_FULL.len().min(7);
    &GIT_SHA_FULL[..len]
}

pub const PLATFORM_SLUG: &str = if cfg!(target_os = "macos") {
    "macos"
} else if cfg!(target_os = "windows") {
    "windows"
} else {
    "linux"
};

pub const PLATFORM_DISPLAY: &str = if cfg!(target_os = "macos") {
    "macOS"
} else if cfg!(target_os = "windows") {
    "Windows"
} else {
    "Linux"
};

#[derive(Debug)]
pub struct Asset {
    pub content_type: &'static str,
    pub body: Cow<'static, [u8]>,
}

impl Asset {
    const fn text(content_type: &'static str, body: String) -> Self {
        Self {
            content_type,
            body: Cow::Owned(body.into_bytes()),
        }
    }

    const fn raw(content_type: &'static str, body: &'static [u8]) -> Self {
        Self {
            content_type,
            body: Cow::Borrowed(body),
        }
    }
}

pub fn render_index() -> String {
    render_index_from(HTML)
}

pub fn render_index_from(source: &str) -> String {
    let brand = crate::brand::brand();
    let html = source
        .replace("__VERSION__", brand.version)
        .replace("__CORE_VERSION__", crate::brand::COMPAT_VERSION)
        .replace("__GIT_SHA__", git_sha_short())
        .replace("__BUILD_DATE__", BUILD_DATE)
        .replace("__ICON_SVG__", brand.assets.icon_svg)
        .replace("__LOGO_SVG__", brand.assets.logo_svg)
        .replace("__PLATFORM_DISPLAY__", PLATFORM_DISPLAY)
        .replace("__PLATFORM__", PLATFORM_SLUG);
    // Why: both of these have to land before the module scripts run — the
    // brand tokens so the first paint is already branded, and the force-dark
    // flag so `theme.js` never resolves the OS preference in the first place.
    let mut head = String::new();
    if !brand.assets.theme_css.is_empty() {
        head.push_str(&format!(
            "<style id=\"brand-theme\">{}</style>",
            brand.assets.theme_css
        ));
    }
    if brand.force_dark {
        head.push_str("<script>window.__SP_FORCE_DARK__ = true;</script>");
    }
    if head.is_empty() {
        html
    } else {
        html.replacen("</head>", &format!("{head}</head>"), 1)
    }
}

fn content_type_for(rel: &str) -> &'static str {
    systemprompt_models::mime::http_content_type(Path::new(rel))
}

pub fn lookup_path(path: &str) -> Option<Asset> {
    if path == "/" || path == "/index.html" {
        return Some(Asset::text("text/html; charset=utf-8", render_index()));
    }
    if let Some(rel) = path.strip_prefix("/assets/")
        && let Some((_, src)) = WEB_TEXT_ASSETS.iter().find(|(n, _)| *n == rel)
    {
        return Some(Asset::text(content_type_for(rel), (*src).to_owned()));
    }
    match path {
        "/assets/fonts/Inter-Regular.woff2" => Some(Asset::raw("font/woff2", FONT_INTER_REGULAR)),
        "/assets/fonts/Inter-Bold.woff2" => Some(Asset::raw("font/woff2", FONT_INTER_BOLD)),
        "/assets/fonts/OpenSans-Regular.woff2" => {
            Some(Asset::raw("font/woff2", FONT_OPENSANS_REGULAR))
        },
        "/assets/fonts/OpenSans-Bold.woff2" => Some(Asset::raw("font/woff2", FONT_OPENSANS_BOLD)),
        _ => None,
    }
}

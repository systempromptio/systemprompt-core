UPDATE agent_tasks SET status = 'TASK_STATE_SUBMITTED' WHERE status = 'TASK_STATE_PENDING';
UPDATE agent_tasks SET status = 'TASK_STATE_FAILED' WHERE status = 'TASK_STATE_UNKNOWN';

ALTER TABLE agent_tasks DROP CONSTRAINT IF EXISTS agent_tasks_status_check;
ALTER TABLE agent_tasks ADD CONSTRAINT agent_tasks_status_check CHECK (
    status IN (
        'TASK_STATE_SUBMITTED', 'TASK_STATE_WORKING', 'TASK_STATE_INPUT_REQUIRED',
        'TASK_STATE_COMPLETED', 'TASK_STATE_CANCELED', 'TASK_STATE_FAILED',
        'TASK_STATE_REJECTED', 'TASK_STATE_AUTH_REQUIRED'
    )
);
